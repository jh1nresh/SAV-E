"""Rebuild the two documented Dihua shopfronts from restored Taipei runtime data.

python build-dihua-north-frontages.py PATH_TO_RESTORED_DATA > dihua-north-frontages.js
Uses the projection, measured wall, terrain and road-exposure checks of the citywide matcher.
"""
from pathlib import Path
import argparse
import json
import runpy

from shapely.geometry import Point, shape

F = runpy.run_path(str(Path(__file__).with_name("build-city170-frontages.py")))
read = F["load_json"]
PACK = "p221_2038"
ROAD = "road/way/1274538025"
# Primary sources identify the ground-floor trade and show the covered frontage.
# Depth and fixtures are schematic; no photo or third-party model is distributed.
SHOPS = [
    ("poi/node/3835269757", "天山行", 200, "food", "南北貨行", "provisions",
     "臺北市友善店家", "https://www.friendlystore.taipei/store/tw/pg1/1/company/8200",
     "https://www.tcavs.tc.edu.tw/upload/1080618111340.pdf#page=40"),
    ("poi/node/3835274357", "高建桶店", 204, "houseware", "竹木器店", "bamboo",
     "臺北旅遊網", "https://www.travel.taipei/file/34995/",
     "https://www.travel.taipei/file/34566/"),
]


def frontage(survey, place, road):
    pin = F["project"](shape(place["geometry"]))
    foot = road.interpolate(road.project(pin))
    length = pin.distance(foot)
    nx, ny = (foot.x - pin.x) / length, (foot.y - pin.y) / length
    buckets = survey.buckets(pin)
    matches = []
    for bucket in buckets:
        for i in bucket.tree.query(pin, predicate="dwithin", distance=6):
            wall = bucket.segments[i]
            a, b = wall.coords
            dx, dy = (b[0] - a[0]) / wall.length, (b[1] - a[1]) / wall.length
            normal = (dy, -dx) if dy * nx - dx * ny >= 0 else (-dy, dx)
            # A pin must project strictly inside one exposed, ground-level bay on its own side of the street.
            offset = (pin.x - a[0]) * dx + (pin.y - a[1]) * dy
            if not (3 < wall.length < 8 and 0 < offset < wall.length and normal[0] * nx + normal[1] * ny > .95):
                continue
            projection = wall.interpolate(offset)
            towards = (projection.x - pin.x) * nx + (projection.y - pin.y) * ny
            if not 0 < towards < length:
                continue
            center = wall.interpolate(.5, normalized=True)
            road_point = road.interpolate(road.project(center))
            base, top = bucket.base[i],bucket.top[i]
            ground = survey.exposure(center, road_point, buckets, normal, base, top)
            if ground is None:
                continue
            row = {"surveyBase":round(base, 3),"surveyTop":round(top, 3),"groundZ":round(ground, 3),
                   "surveyTile":bucket.tile}
            # Inset both ends from adjoining tenants. Keep the illustrated arcade off the 5 m carriageway.
            F["update_wall"](row, center, wall, .07, wall.length - .07, normal)
            row["arcadeDepth"] = round(min(1.45, center.distance(road_point) - 2.5 - .3), 2)
            if row["arcadeDepth"] >= .8:
                matches.append(row)
    if len(matches) != 1:
        raise ValueError(f"{place['id']}: expected one exposed measured bay, got {len(matches)}")
    return matches[0]


def build(data):
    features = {f["id"]:f for f in read(data / "city170" / (PACK + ".json.gz"))["features"]["features"]}
    road = F["project"](shape(features[ROAD]["geometry"]))
    survey = F["Survey"](data)
    rows = []
    for ident, name, house, category, label, design, source, url, arcade in SHOPS:
        place = features[ident]
        props = place["properties"]
        if props["name"] != name or f"{house} 號" not in props["detail"]:
            raise ValueError(f"Changed shop identity: {ident}")
        row = frontage(survey, place, road)
        row.update(id=ident, name=name, category=category, categoryLabel=label, detail=props["detail"],
                   poiCenter=place["geometry"]["coordinates"], buildingId=None, streetId=ROAD,
                   street=features[ROAD]["properties"]["name"], district="大同區", pack=PACK,
                   evidence="documented-shop-and-exposed-survey-bay", source=source, url=url,
                   arcadeSource=arcade, frontDesign=design)
        rows.append(row)
    return rows


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data", type=Path)
    print("// Generated by scripts/build-dihua-north-frontages.py. Arcade depth and fixtures are illustrative.")
    print("export const dihuaNorthFronts = " + json.dumps(build(parser.parse_args().data), ensure_ascii=False, indent=2) + ";")
