"""Build the Taipei City subset of Taipei Metro's public exit coordinates.

Inputs: the official CSV (CP950) and the same districts.geojson used on the map.
Usage: python build-taipei-metro-exits.py exits.csv districts.geojson metro-exit-data.js
"""

import argparse
import csv
import hashlib
import io
import json
import re
from pathlib import Path

from shapely.geometry import Point, shape


DATASET = "https://data.taipei/dataset/detail?id=cfa4778c-62c1-497b-b704-756231de348b"


def station_name(name, number):
    suffix = "出口" if number == "0" else number
    if not name.endswith(suffix):
        raise ValueError(f"Exit label and number disagree: {name}, {number}")
    station = name.removesuffix(suffix).removesuffix("出口").strip()
    if not station or station == name:
        raise ValueError(f"Unrecognized station name: {name}, {number}")
    return station


def build(raw, district_data):
    districts = [(f["properties"]["name"], shape(f["geometry"]))
                 for f in district_data["features"]]
    rows = []
    identities = set()
    coordinates = set()
    source = csv.DictReader(io.StringIO(raw.decode("cp950")))
    for row in source:
        name, number = row["出入口名稱"].strip(), row["出入口編號"].strip()
        station = station_name(name, number)
        accessible = row["是否為無障礙用"].strip()
        if accessible not in {"是", "否"} or not re.fullmatch(r"[A-Z0-9][A-Z0-9]?", number):
            raise ValueError(f"Unsupported exit record: {row}")
        lon, lat = float(row["經度"]), float(row["緯度"])
        if not (120 < lon < 123 and 23 < lat < 26):
            raise ValueError(f"Invalid exit coordinate: {row}")
        point = Point(lon, lat)
        match = [name for name, district in districts if district.covers(point)]
        if not match:
            continue
        identity = station, number
        if len(match) != 1 or identity in identities or (lon, lat) in coordinates:
            raise ValueError(f"Ambiguous Taipei exit record: {row}")
        identities.add(identity)
        coordinates.add((lon, lat))
        rows.append([station, number, lon, lat, match[0], accessible == "是"])
    if not rows:
        raise ValueError("No exits match the supplied Taipei districts")
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("csv", "districts", "output"):
        parser.add_argument(name, type=Path)
    args = parser.parse_args()
    raw = args.csv.read_bytes()
    rows = build(raw, json.loads(args.districts.read_bytes()))
    encoded = ",\n".join("  " + json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in rows)
    args.output.write_text(
        "// Taipei Rapid Transit Corporation · Open Government Data License 1.0\n"
        f"// {DATASET}\n"
        f"// Source CSV SHA-256: {hashlib.sha256(raw).hexdigest()}\n"
        "// Generated by scripts/build-taipei-metro-exits.py.\n"
        f"export default [\n{encoded},\n];\n",
        encoding="utf-8",
    )
    print(f"{len(rows)} exits in {len({row[4] for row in rows})} Taipei districts")


if __name__ == "__main__":
    main()
