"""Find legacy illustrative tree roots inside at-grade playing surfaces and road paint.

Run from TaipeiPocketCity with Shapely 2:
  python scripts/build-taipei-tree-clearance.py data taipei-tree-clearance-data.js
Only grove sprites and old scenery tree placements are inputs, never the surveyed tree inventory.
"""
import argparse
import gzip
import json
import math
from pathlib import Path
import runpy

import shapely
from shapely.geometry import shape

ROOT = Path(__file__).resolve().parents[1]
GROUND = runpy.run_path(str(ROOT/'scripts/build-xinyi-street-ground.py'))
above_ground = runpy.run_path(str(ROOT/'scripts/build-city170-grade.py'))['above_or_below_ground']
SPORTS = {'basketball','tennis','volleyball','badminton','baseball','softball','soccer','handball',
          'rugby','rugby_union','field_hockey','roller_skating','skateboard','running','athletics'}


def read(path):
    return json.loads(gzip.decompress(path.read_bytes()))


def roots(data, pack_ids):
    points = set()
    for pack in pack_ids:
        for features in read(data/'city170-prepared'/f'{pack[1:]}.json.gz').values():
            points.update(tuple(f['geometry']['coordinates']) for f in features if f['properties']['kind']=='grove-tree')
    for pack in pack_ids:
        life = read(data/'city170-life'/f'{pack}.json.gz')
        points.update((x,y) for x,y,kind,*_ in life['objects'].values() if kind=='tree')
    return sorted(points)


def is_playing_surface(feature, elevated):
    props, geometry = feature['properties'], feature['geometry']
    if props['kind'] != 'pitch' or feature['id'] in elevated or above_ground(props):
        return False
    sports = set(props.get('sport','').split(';'))
    if props['category']=='track':
        return (geometry['type']=='Polygon' and len(geometry['coordinates'])==2
                and bool(sports & {'running','athletics','runing'}))
    return (props['category']=='pitch' and geometry['type'] in ('Polygon','MultiPolygon')
            and bool(sports & SPORTS))


def collisions(data, assets):
    packs = json.loads((data/'city170/index.json').read_text())['packs']
    coords = roots(data, [p['id'] for p in packs])
    x, y = zip(*coords)
    geographic = shapely.STRtree(shapely.points(x, y))
    ox, oy = GROUND['ORIGIN']
    grid = shapely.STRtree(shapely.points([lon*1e6-ox for lon in x], [lat*1e6-oy for lat in y]))
    road, sport = set(), set()
    district_inputs = json.loads((ROOT/'scripts/taipei-street-ground-receipts.json').read_text())
    for district in sorted(district_inputs['districts']):
        path = assets/f'{district}-street-ground.json.gz'
        for encoded in read(path)['road']:
            # Five microdegrees leave a kerb margin of at least half a metre.
            pavement = GROUND['packed_polygon'](encoded).buffer(-5)
            road.update(grid.query(pavement, predicate='contains'))
    grade = json.loads((ROOT/'city170-grade-ids.js').read_text().split('export default ')[1].strip().rstrip(';'))
    elevated = {f'{prefix}/{i}' for prefix,ids in grade.items() for i in ids}
    for pack in packs:
        for feature in read(data/'city170'/pack['url'])['features']['features']:
            if is_playing_surface(feature, elevated):
                surface = shape(feature['geometry'])
                sport.update(geographic.query(surface, predicate='contains'))
    return {name:{coords[i] for i in ids} for name,ids in [('road', road),('sport', sport)]}


def write(groups, output):
    # Store individual roots, not a landuse mask. A tree on a neighbouring
    # sidewalk or in the centre of a track with an unmapped infield stays put.
    coords = sorted(set.union(*groups.values()))
    # Match Math.round in the renderer even when a source coordinate ends in a half.
    points = [(math.floor(x*1e7+.5),math.floor(y*1e7+.5)) for x,y in coords]
    if len(points)!=len(set(points)):
        raise ValueError('More than one root at the same encoded position')
    rows = [','.join(f'{x-1210000000},{y-250000000}' for x,y in points[i:i+10]) for i in range(0,len(points),10)]
    output.write_text('// Generated by scripts/build-taipei-tree-clearance.py from the Taipei street atlas.\n'
                      'export default [\n'+',\n'.join(rows)+'\n];\n')
    print({key:len(value) for key,value in groups.items()}, 'unique',len(points))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('data',type=Path)
    parser.add_argument('output',type=Path)
    args=parser.parse_args()
    write(collisions(args.data,ROOT/'assets'),args.output)
