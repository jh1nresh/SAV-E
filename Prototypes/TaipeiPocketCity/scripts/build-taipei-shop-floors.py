"""Build public shop floor labels from the original OSM POIs in the Taipei shop index.

Usage: python build-taipei-shop-floors.py taipei.json.gz RESTORED_DATA OUTPUT_JS
Names, house numbers and nearby businesses are never used to infer a level.
"""
import argparse
from collections import defaultdict
import gzip
import hashlib
import json
from pathlib import Path
import re
import unicodedata

import ijson


def numbers(value, posted):
    values = set()
    for raw in unicodedata.normalize('NFKC',value).upper().split(';'):
        raw = raw.strip()
        if posted:
            floor = re.fullmatch(r'(?:B|地下)([1-9]\d?)(?:F|樓|層)?',raw)
            if floor:
                values.add(-int(floor[1]))
                continue
            match = re.fullmatch(r'(-?[1-9]\d?)(?:F|樓|層)?',raw)
        else:
            match = re.fullmatch(r'(-?(?:0|[1-9]\d?))',raw)
        if not match:
            return None
        n = int(match[1])
        values.add(n if posted or n<0 else n+1)
    return values


def floor_label(tags):
    posted = [numbers(tags[k],True) for k in ('addr:floor','level:ref') if tags.get(k)]
    # level:ref and postal floors can use local numbering. If both are present,
    # insist that the explicit descriptions match.
    if posted and (None in posted or any(s!=posted[0] for s in posted)):
        return
    levels = numbers(tags['level'],False) if 'level' in tags else None
    if 'level' in tags and (not levels or (posted and posted[0]!=levels)):
        return
    if posted:
        floors = sorted(posted[0])
        if len(floors)>3:
            return
        return '、'.join(f'B{-n}' if n<0 else f'{n}F' for n in floors)
    # An OSM ordinal need not equal the public-facing floor number (skipped floors).
    if levels:
        if levels=={1}: return '地面層'
        if min(levels)>1: return '樓上'
        if max(levels)<0: return '地下樓層'


def build(source,data):
    meta=json.loads((data/'city170/index.json').read_bytes())
    with gzip.open(source,'rb') as src:
        if hashlib.file_digest(src,'sha256').hexdigest()!=meta['source']['provenance']['taipeiExtractUncompressedSHA256']:
            raise ValueError('Wrong source edition for the Taipei shop index')
    with gzip.open(data/'city170-frontages/search.json.gz') as src:
        wanted={r[6] for r in json.load(src)}
    grouped=defaultdict(list)
    with gzip.open(source,'rb') as src:
        for r in ijson.items(src,'elements.item',use_float=True):
            if f"poi/{r['type']}/{r['id']}" not in wanted:
                continue
            label=floor_label(r.get('tags',{}))
            if label:
                grouped[(label,r['type'])].append(r['id'])
    return [[label,kind,' '.join(map(str,sorted(ids)))] for (label,kind),ids in sorted(grouped.items())]


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for key in ('source','data','output'):
        p.add_argument(key,type=Path)
    args=p.parse_args()
    groups=build(args.source,args.data)
    args.output.write_text('// OpenStreetMap contributors · ODbL. Generated by scripts/build-taipei-shop-floors.py.\n'
        +'export default '+json.dumps(groups,ensure_ascii=False,separators=(',',':'))+';\n')
