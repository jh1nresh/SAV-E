"""Bundle missing Terrarium heights for Taipei's existing offline map footprint.

Run after prepare_data.py. Pass a download cache outside the repository.
Existing calibrated street and landmark tiles retain precedence in app.js.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import runpy
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
relief = runpy.run_path(str(ROOT / 'tools/build-taiwan-relief.py'))


def build(cache):
    regions = ROOT / 'cities/map-tiles'
    footprint = json.loads((regions / 'taipei-bundled/index.json').read_text())
    landmarks = json.loads((regions / 'index.json').read_text())
    city = json.loads((ROOT / 'data/city-streets/index.json').read_text())
    present = {(14, x, y) for x, y in landmarks['tiles']}
    present.update((14, *map(int, key.split('/'))) for key in city['terrainTiles'])
    required = {tuple(key) for key in footprint['tiles'] if 10 <= key[0] <= 14}
    tiles = sorted(required - present)
    target = ROOT / 'taiwan/taipei-relief'
    (target / 'dem').mkdir(parents=True, exist_ok=True)
    cache.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=5) as pool:
        list(pool.map(lambda tile: relief['download_tile'](tile, cache), tiles))
    names = ['-'.join(map(str, key)) for key in tiles]
    digest = hashlib.sha256()
    source_digest = hashlib.sha256()
    for name in names:
        path = target / 'dem' / (name + '.png')
        raw = cache / path.name
        source_digest.update(raw.read_bytes())
        with Image.open(raw) as image:
            rgb = np.asarray(image.convert('RGB'), dtype=np.int32)
        encoded = rgb[:, :, 0]*65536 + rgb[:, :, 1]*256 + rgb[:, :, 2]
        # Quarter metres suffice for landscape relief. Keep RGB carries at 256 m
        # and below sea level correct; accepted street DEMs are never repacked.
        rounded = (encoded + 32) // 64 * 64
        channels = np.stack((rounded >> 16, (rounded >> 8) % 256, rounded % 256), axis=2)
        Image.fromarray(channels.astype(np.uint8)).save(path, optimize=True)
        digest.update(path.read_bytes())
    manifest = dict(terrainSource=relief['TERRAIN'], sourceSha256=source_digest.hexdigest(),
                    resolutionMetres=.25, demSha256=digest.hexdigest(), dem=names)
    (target / 'index.js').write_text('// Generated by tools/build-taipei-relief.py\nexport default '
                                     + json.dumps(manifest, indent=2) + ';\n')
    print(f'{len(names)} supplementary DEM tiles, {len(required)} local terrain tiles at zoom 10–14')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', required=True, type=Path)
    build(parser.parse_args().cache)
